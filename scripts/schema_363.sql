CREATE SCHEMA IF NOT EXISTS cleantech;
SET search_path TO cleantech, public;

-- 1. Startups Entity Table
CREATE TABLE IF NOT EXISTS startups (
    startup_id VARCHAR(64) PRIMARY KEY,
    company_name TEXT NOT NULL,
    cohort_year INTEGER NOT NULL,
    founder TEXT,
    raw_data_dir TEXT,
    evaluation_status VARCHAR(30) DEFAULT 'PENDING'
        CHECK (evaluation_status IN ('PENDING', 'DETERMINISTIC_MAPPED', 'AI_BACKFILLED', 'HUMAN_VERIFIED', 'LOCKED')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. Rubric Catalog Reference Table (363 Questions)
CREATE TABLE IF NOT EXISTS rubric_catalog (
    question_id VARCHAR(32) PRIMARY KEY,
    orig_q_id VARCHAR(32) NOT NULL,
    cat_code VARCHAR(10) NOT NULL,
    category_name TEXT NOT NULL,
    data_type VARCHAR(16) NOT NULL CHECK (data_type IN ('BINARY', 'INTEGER')),
    verification_role VARCHAR(10) NOT NULL CHECK (verification_role IN ('AI', 'HUMAN')),
    question_text TEXT NOT NULL,
    weight NUMERIC(5,4) DEFAULT 1.0000
);

