-- 6. AI Backfill Target Worklist View (Filters ONLY Ambiguous -1, Skips NULL Missing)
CREATE OR REPLACE VIEW v_ai_backfill_queue AS
SELECT 
    s.startup_id,
    s.company_name,
    s.cohort_year,
    s.raw_data_dir,
    rc.question_id,
    rc.cat_code,
    rc.verification_role,
    rc.question_text
FROM startup_scores_363 sc
JOIN startups s ON sc.startup_id = s.startup_id,
LATERAL jsonb_each_text(to_jsonb(sc) - '{startup_id,total_binary_passed,ai_auto_passed,human_verified_passed,total_score_pct,resolved_count,ambiguous_count,missing_legacy_count,updated_at}'::text[]) q
JOIN rubric_catalog rc ON LOWER(rc.question_id) = q.key
WHERE q.value = '-1' AND rc.verification_role = 'AI';

-- 7. Analytical Summary View
CREATE OR REPLACE VIEW v_startup_summary AS
SELECT 
    s.startup_id,
    s.company_name,
    s.cohort_year,
    s.founder,
    s.evaluation_status,
    sc.resolved_count,
    sc.ambiguous_count,
    sc.missing_legacy_count,
    sc.total_binary_passed,
    sc.ai_auto_passed,
    sc.human_verified_passed,
    sc.total_score_pct,
    COUNT(e.evidence_id) AS total_evidence_citations,
    ROUND(AVG(e.confidence), 3) AS avg_ai_confidence,
    SUM(CASE WHEN e.confidence < 0.75 THEN 1 ELSE 0 END) AS low_confidence_count,
    sc.updated_at
FROM startups s
LEFT JOIN startup_scores_363 sc ON s.startup_id = sc.startup_id
LEFT JOIN evaluation_evidence e ON s.startup_id = e.startup_id
GROUP BY s.startup_id, s.company_name, s.cohort_year, s.founder, s.evaluation_status,
         sc.resolved_count, sc.ambiguous_count, sc.missing_legacy_count,
         sc.total_binary_passed, sc.ai_auto_passed, sc.human_verified_passed, sc.total_score_pct, sc.updated_at;
